"""SoloLedger demo data — load/remove sample transactions.

Single source of truth for the `llc demo` dataset (previously inline in
app/main.py). Demo entries live in ONE bounded block inside
ledger/transactions.beancount:

    ;; === SoloLedger Demo Data ===...   <- START_MARKER
    ...entries...
    ;; === End SoloLedger Demo Data ===  <- END_MARKER

Removal deletes only the bounded block, so real transactions appended
after the demo section are never touched. Files written by older
versions have no end marker — for those, removal falls back to matching
the exact known demo directives and leaves everything else in place.
"""

