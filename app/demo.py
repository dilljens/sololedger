def _render_entry(date: str, payee: str, narration: str,
                  postings: list[tuple[str, str]]) -> str:
    """Render one directive exactly as the demo loader writes it."""
    payee = payee.replace('"', '\\"')
    narration = narration.replace('"', '\\"')
    lines = [f'{date} * "{payee}" "{narration}"']
    for account, amount in postings:
        lines.append(f"  {account:45s}  {amount}")
    return "\n".join(lines) + "\n"


def has_demo(content: str) -> bool:
    """True if the ledger text contains the demo block."""
    return START_MARKER in content


def load_demo(tx_path: str | Path) -> int:
    """Append the bounded demo block. Returns entry count, -1 if present."""
    path = Path(tx_path)
    content = path.read_text()
    if has_demo(content):
        return -1
    with open(path, "a") as f:
        f.write("\n")
        f.write(";; === SoloLedger Demo Data ==========================================\n")
        f.write(";; Generated by `llc demo` — safe to delete with `llc demo --remove`\n")
        f.write(";; ==================================================================\n")
        f.write("\n")
        for date, payee, narration, postings in DEMO_ENTRIES:
            f.write(_render_entry(date, payee, narration, postings))
            f.write("\n")
        f.write(";; === End SoloLedger Demo Data ========================================\n")
    return len(DEMO_ENTRIES)


def remove_demo(tx_path: str | Path) -> int:
    """Remove the demo block, keeping real transactions. Returns # removed."""
    path = Path(tx_path)
    content = path.read_text()
    if not has_demo(content):
        return 0

    if END_MARKER in content:
        return _remove_bounded(path, content)

    # Legacy file (no end marker): delete only the exact known directives.
    removed = 0
    for date, payee, narration, postings in DEMO_ENTRIES:
        block = _render_entry(date, payee, narration, postings)
        if block in content:
            content = content.replace(block, "", 1)
            removed += 1
    # Drop the now-orphaned marker header lines.
    lines = [ln for ln in content.splitlines(keepends=True)
             if START_MARKER not in ln
             and "Generated by `llc demo`" not in ln
             and not re.fullmatch(r";; =+\n", ln)]
    content = "".join(lines)
    content = re.sub(r"\n{3,}", "\n\n", content)
    content = re.sub(r"\n+$", "\n", content) if content else content
    path.write_text(content)
    return removed


def _remove_bounded(path: Path, content: str) -> int:
    """Cut from the START_MARKER line through the END_MARKER line."""
    lines = content.splitlines(keepends=True)
    start = next(i for i, ln in enumerate(lines) if START_MARKER in ln)
    end = next(i for i, ln in enumerate(lines) if END_MARKER in ln)
    removed_block = "".join(lines[start:end + 1])
    removed = len(re.findall(r"(?m)^\d{4}-\d{2}-\d{2} \*", removed_block))
    del lines[start:end + 1]
    # Swallow one leftover blank line so no triple gap remains.
    if start < len(lines) and lines[start].strip() == "" \
            and start > 0 and lines[start - 1].strip() == "":
        del lines[start]
    content = "".join(lines)
    content = re.sub(r"\n{3,}", "\n\n", content)
    content = re.sub(r"\n+$", "\n", content) if content else content
    path.write_text(content)
    return removed
