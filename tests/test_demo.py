class TestDemoCLI:
    def test_remove_keeps_real_cli(self, tmp_path):
        from app.main import cli
        cfg = _make_cli_ledger(tmp_path, legacy=True)
        result = CliRunner().invoke(cli, ["-c", cfg, "demo", "--remove"])
        assert result.exit_code == 0, result.output
        assert "real entries kept" in result.output
        tx = tmp_path / "ledger" / "transactions.beancount"
        assert "Estimated tax payment Q3 2026" in tx.read_text()
        assert "Acme Corp" not in tx.read_text()

    def test_fresh_keeps_real_cli(self, tmp_path):
        from app.main import cli
        cfg = _make_cli_ledger(tmp_path, legacy=False)
        runner = CliRunner()
        assert runner.invoke(cli, ["-c", cfg, "demo"]).exit_code == 0
        tx = tmp_path / "ledger" / "transactions.beancount"
        with open(tx, "a") as f:
            f.write("\n" + REAL_TXN)
        result = runner.invoke(cli, ["-c", cfg, "demo", "--fresh"])
        assert result.exit_code == 0, result.output
        content = tx.read_text()
        assert "Estimated tax payment Q3 2026" in content  # real kept
        assert content.count(START_MARKER) == 1  # demo reloaded once
        assert END_MARKER in content

    def test_status_nudges_on_placeholder_identity(self, tmp_path):
        from app.main import cli
        cfg = _make_cli_ledger(tmp_path, legacy=False)
        # Rewrite config with placeholder identity
        cfg_text = open(cfg).read().replace('name = "Test LLC"',
                                            'name = "Your LLC Name Here"')
        open(cfg, "w").write(cfg_text)
        result = CliRunner().invoke(cli, ["-c", cfg, "status"])
        assert result.exit_code == 0, result.output
        assert "llc init" in result.output

    def test_status_quiet_with_real_identity(self, tmp_path):
        from app.main import cli
        cfg = _make_cli_ledger(tmp_path, legacy=False)
        result = CliRunner().invoke(cli, ["-c", cfg, "status"])
        assert result.exit_code == 0, result.output
        assert "Business identity not set" not in result.output
