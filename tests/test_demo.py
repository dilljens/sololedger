    opens = "\n".join(f"1970-01-01 open {a}" for a in accounts)
    (ledger_dir / "main.beancount").write_text(
        'option "title" "Test"\n\n' + opens + '\ninclude "transactions.beancount"\n')
    tx = ledger_dir / "transactions.beancount"
    if legacy:
        _write_legacy_with_real(tx)
